#!/usr/bin/env bash
set -euo pipefail
# Compile only this helper, with outputs outside the source checkout.
: "${JAVA_HOME:?Use JDK 17; generated bytecode stays compatible with JDK 8}"
: "${SPARK_HOME:?Pinned Spark 3.5.9 distribution}"
: "${PAIMON_JAR:?Independently built Spark3.5 Paimon artifact}"
: "${HARNESS_BUILD:?Dedicated scratch directory, e.g. /data/commit-memory/harness-build}"
test -f "$SPARK_HOME/jars/spark-core_2.12-3.5.9.jar"
test -f "$PAIMON_JAR"
test ! -e "$HARNESS_BUILD/commit-memory-harness.jar"
mkdir -p "$HARNESS_BUILD/classes"
script_dir="$(cd -- "$(dirname -- "$0")" && pwd)"
"$JAVA_HOME/bin/javac" -J-Xmx256m -source 8 -target 8 -encoding UTF-8 \
  -cp "$PAIMON_JAR:$SPARK_HOME/jars/*" -d "$HARNESS_BUILD/classes" "$script_dir/CommitMemoryBench.java" \
  > "$HARNESS_BUILD/javac.raw.log" 2>&1
"$JAVA_HOME/bin/jar" cf "$HARNESS_BUILD/commit-memory-harness.jar" -C "$HARNESS_BUILD/classes" .
sha256sum "$script_dir/CommitMemoryBench.java" "$PAIMON_JAR" "$HARNESS_BUILD/commit-memory-harness.jar" \
  > "$HARNESS_BUILD/build.sha256"
